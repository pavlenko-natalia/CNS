# Опис
#
# Кілька «роторів» — перестановок, які обертаються після кожного символу. Ротор 1 — кожен крок, ротор 2 — після повного оберту ротора 1, ротор 3 — після повного оберту ротора 2 (одометр). Це поліалфавітна підстановка, де період = 26^k.
#
# Вразливості
#
# Відома конфігурація роторів (як у завданні) → повністю детерміновано, треба просто запустити шифр у зворотному напрямку.
# Невідома конфігурація — brute force роторів (26³), або статистика; але у нас конфігурація дана.
# Класичний Enigma: відомі вразливості через crib (відомий фрагмент) + reflector не дозволяє літері зашифруватися в себе.
# Тут — спрощена версія, тому основне — акуратно реалізувати реверс.
#
# Умова: ротори фіксовані, старт 0,0,0. Cipher: HKV{BSBU-B-SJYZNNB-DNFW-IXH-YTA-RPL-RTXOLWFQ}.

rotor1 = "MACHINEBDFGJKLOPQRSTUVWXYZ"
rotor2 = "ORBITACDEFGHJKLMNPQSUVWXYZ"
rotor3 = "CIPHERABDFGJKLMNOQSTUVWXYZ"
alpha  = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
ct     = "HKV{BSBU-B-SJYZNNB-DNFW-IXH-YTA-RPL-RTXOLWFQ}"

r1 = r2 = r3 = 0
pt = ""
for c in ct:
    if c not in alpha:
        pt += c; continue
    r1 += 1
    r2 = r1 // 26
    r3 = r1 // (26*26)          # у завданні ротор 3 стартує з 0, але за логікою одометра треба /(26*26)
    # КРОК 3 → 2 → 1 (у зворотному порядку)
    i3 = rotor3.find(c)                          # index у ротор3
    L3 = alpha[i3]
    i2 = rotor2.find(L3) - r2
    L2 = alpha[i2]
    i1 = rotor1.find(L2) - r1
    p  = alpha[i1 % 26]
    pt += p
print(pt)
